# list comprension vs generator expression

# | List Comprehension         | Generator Expression          |
# | -------------------------- | ----------------------------- |
# | `[]`                       | `()`                          |
# | Creates all values         | Creates values on demand      |
# | Uses more memory           | Memory efficient              |
# | Can be indexed             | Cannot directly be indexed    |
# | Reusable after creation    | Usually consumed once         |
# | Good for small/medium data | Good for large/streaming data |

# example:
numbers=[x*2 for x in range(1000000)]
# create a large list

# whereas:
numbers=(x*2 for x in range(1000000))
# create a generator

