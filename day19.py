# Generator Function vs Generator Expression

# generator function

def even_numbers(n):
    for i in range(n):
        if n%2==0:
            yield n


# generator expression
even_numbers=(x for x in range(10) if x%2==0)

# when to use which?
# use a generator expression for simple logic.
# use a generator fonction whwn the logic is more complex.

