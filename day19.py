# Lazy Data Processing Pipeline

# Create a pipeline that:

    # Step 1 — Generate numbers
    # 1 → 2 → 3 → ... → 100

    # Step 2 — Keep only even numbers
    # 2, 4, 6, 8...

    # Step 3 — Square them
    # 4, 16, 36, 64...

    # Step 4 — Keep values greater than 100
    # 144, 196, 256...

# Use generators, not lists.
# The structure should look like:

    # numbers
    #    ↓
    # even numbers
    #    ↓
    # squares
    #    ↓
    # greater than 100
    #    ↓
    # output

numbers=(x for x in range(1,101))
even_numbers=(x for x in numbers if x%2==0)
squares=(x*x for x in even_numbers)
greater_than_100=(x for x in squares if x>100)
for value in greater_than_100:
    print(value)

# OR

def lazy_pipeline(start,end):
    for i in range(start,end):
        if i%2==0:
            if i**2>100:
                yield i**2
for value in lazy_pipeline(1,101):
    print(value)

