# Create a generator called unique_values(numbers) that yields each value only once, preserving its original order.

def unique_values(numbers):
    unique={}
    for i in numbers:
        if i not in unique:
            unique[i]=1
    for i in unique:
        yield i
numbers = [1, 2, 2, 3, 1, 4, 3, 5]

for value in unique_values(numbers):
    print(value)

# or

def unique_values(numbers):
    seen = set()

    for number in numbers:
        if number not in seen:
            seen.add(number)
            yield number

