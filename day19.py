# Generator Pipeline
# this is an important real-world concept

# you can connect generator together.
numbers=range(1,11)
even_numbers=(x for x in numbers if x%2==0)
squares=(x*x for x in even_numbers)         #even_numbers generator is exhausted
for x in squares:                        
    print(x)                  # squares generator is now exhausted

# output:
# 4
# 16
# 36
# 64
# 100

# think of it as:

# Original Data
#      ↓
# Filter
#      ↓
# Transform
#      ↓
# Output

# this idea is extremely useful in data processing and ML pipelines.

