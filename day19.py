# generator expression:
# a generator expression looks very similar to list comprehension.

# list comprehension:
numbers=[x*2 for x in range(5)]
print(numbers)
# it create an entire list immediately.

# output:
# [0, 2, 4, 6, 8]

# generator expresstion
numbers=(x*2 for x in range(5))
print(numbers)
# the value aren't generated yet

# output:
# <generator object <genexpr> at 0x000002DB0608DBE0>

# you can consume them by:
for num in numbers:
    print(num)

# output:
# 0
# 2
# 4
# 6
# 8


